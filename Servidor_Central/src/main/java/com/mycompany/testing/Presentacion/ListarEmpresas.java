    private void tblMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMouseClicked
        // TODO add your handling code here:
        int filaSeleccionada = tbl.getSelectedRow();
        
        if (filaSeleccionada != -1){
            String nombre = tbl.getValueAt(filaSeleccionada,0).toString();
            String creacion = tbl.getValueAt(filaSeleccionada,1).toString();

            txtNombre.setText(nombre);
            txtCreacion.setText(creacion);
        }
    }//GEN-LAST:event_tblMouseClicked

    private void cargarTabla(){
        try {
            // 1. Obtener la interfaz del controlador a través de la fábrica
            IControlador ic = Fabrica.getInstance().getIControlador();

            // 2. Traer la lista de DataTypes
            List<DTempresa> lista = ic.listarEmpresas();

            // 3. Obtener el modelo de la tabla existente
            DefaultTableModel model = (DefaultTableModel) tbl.getModel();

            // 4. Limpiar las filas previas
            model.setRowCount(0);

            // 5. Cargar los nuevos datos
            for (DTempresa e : lista) {
                model.addRow(new Object[]{ e.getNombre(), e.getCreacion() });
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, 
                "Error al actualizar la tabla: " + e.getMessage(), 
                "Error", 
                JOptionPane.ERROR_MESSAGE);
        }
    }
    
    

