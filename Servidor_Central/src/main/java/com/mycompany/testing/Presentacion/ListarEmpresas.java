    private void btnBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarActionPerformed
        try {
            // 1. Obtener el nombre de los campos de texto
            String nombre = txtNombre.getText().trim();

            // 2. Validar que haya un nombre seleccionado/ingresado
            if (nombre.isEmpty()) {
                JOptionPane.showMessageDialog(this, 
                    "Debe seleccionar una empresa de la tabla para eliminar.", 
                    "Advertencia", 
                    JOptionPane.WARNING_MESSAGE);
                return;
            }

            // 3. Confirmación de seguridad
            int respuesta = JOptionPane.showConfirmDialog(
                this, 
                "¿Está seguro de que desea eliminar la empresa '" + nombre + "'?", 
                "Confirmar eliminación", 
                JOptionPane.YES_NO_OPTION, 
                JOptionPane.QUESTION_MESSAGE
            );

            // Si el usuario hace clic en "Sí" (YES_OPTION)
            if (respuesta == JOptionPane.YES_OPTION) {

                // 4. Invocar al controlador mediante la Fábrica
                IControlador ic = Fabrica.getInstance().getIControlador();
                ic.eliminarEmpresa(nombre);

                // 5. Notificar al usuario
                JOptionPane.showMessageDialog(this, 
                    "Empresa eliminada correctamente.", 
                    "Éxito", 
                    JOptionPane.INFORMATION_MESSAGE);

                // 6. Refrescar la tabla y resetear los campos
                cargarTabla();
                txtNombre.setText("");
                txtCreacion.setText("");
            }

        } catch (Exception e) {JOptionPane.showMessageDialog(this,"Error al eliminar la empresa: " + e.getMessage(),"Error",JOptionPane.ERROR_MESSAGE);
    }
        
    }//GEN-LAST:event_btnBorrarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
        try {
            // 1. Obtener los datos de los campos de texto
            String nombre = txtNombre.getText().trim();
            String creacion = txtCreacion.getText().trim();

            // 2. Validar que no estén vacíos
            if (nombre.isEmpty() || creacion.isEmpty()) {
                JOptionPane.showMessageDialog(this,"Debe seleccionar una empresa de la tabla y completar los datos.","Advertencia",JOptionPane.WARNING_MESSAGE);
                return;
            }

            int anioCreacion = Integer.parseInt(creacion);

            // 3. Invocar al controlador mediante la Fábrica
            IControlador ic = Fabrica.getInstance().getIControlador();
            ic.editarEmpresa(nombre, anioCreacion);

            // 4. Notificar al usuario
            JOptionPane.showMessageDialog(this,"Empresa modificada correctamente.","Éxito",JOptionPane.INFORMATION_MESSAGE);

            // 5. Refrescar la tabla y limpiar campos
            cargarTabla();
            txtNombre.setText("");
            txtCreacion.setText("");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,"El año de creación debe ser un número entero válido.","Error de formato", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {JOptionPane.showMessageDialog(this,"Error al editar: " + e.getMessage(),"Error",JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEditarActionPerformed

